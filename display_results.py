#!/usr/bin/env python3

import argparse
import numpy as np
import matplotlib.pyplot as plt

ExpectedProbabilities = np.array([ 2.78,  5.56,  8.33, 11.11, 13.89, 16.87, 13.89, 11.11, 8.33, 5.56,  2.78 ]) / 100
XAxisTicks = [str(i) for i in range(2,13)]

# Read in data from the CSV file
# CSV File Layout:
# Line 0: Header, all possible dice values from 2-12
# Line 1: Count of each dice total seen
# Line 2 Onwards: Repeat of line 1 for each game saved
def ReadInfiniteFile():
    # Read the CSV
    data = np.loadtxt("games/Infinite_File.csv", delimiter=",", dtype=int)

    bins = data[0, :]
    frequencies = data[1:, :]
    total_frequencies = np.sum(frequencies, axis=0)
    return bins, frequencies, total_frequencies

# Given the number of dice rolls completed through all games, what does the expected bar chart look like
def GetBellCurve(total_frequencies):
    sum = np.sum(total_frequencies)
    return sum * ExpectedProbabilities

# Wrapper for matplotlib.plot.bar
def DrawBarChart(axis, bins, frequencies, label="", alpha=1.0):
    axis.bar(bins, frequencies, tick_label=XAxisTicks, label=label, alpha=alpha, linewidth=1, edgecolor='black')

# Add labels to the bar chart with all games added together
def LabelTotalBarChart(axis):
    axis.set_title("Cumulative Dice Rolls")
    axis.set_xlabel("Dice Value")
    axis.set_ylabel("Number of times seen")
    axis.legend()

# Add labels to the bar chart with all games overlaid each other
def LabelIndividualGameBarChart(axis):
    axis.set_title("Overlaid Game Dice Rolls")
    axis.set_xlabel("Dice Value")
    axis.set_ylabel("Number of times seen")

# This tool reads in the infinite file generated by the dice counter CLI and creates two bar charts.
# Bar chart one contains the dice rolls overlaid over each other
# Bar chart two contains the cumulative sum of all dice roll totals from all games, and the expected totals given ideal dice and perfect rolls
def Main(filePath):
    bins, frequencies, total_frequencies = ReadInfiniteFile()

    # Create 2 plots, stacked vertically
    fig, (stacked_chart, total_chart) = plt.subplots(2, 1, figsize=(6, 12))

    DrawBarChart(total_chart, bins, total_frequencies, label = "Our")
    total_chart.bar(bins, GetBellCurve(total_frequencies), label = "Expected", alpha = 0.3, linewidth=1, hatch='x', hatch_linewidth=1, fill=False)

    for eachGame in frequencies:
        DrawBarChart(stacked_chart, bins, eachGame, alpha = 0.3)

    LabelIndividualGameBarChart(stacked_chart)
    LabelTotalBarChart(total_chart)

    plt.tight_layout()
    plt.savefig(filePath + "/DiceCounterOutput.png")
    plt.show()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("filepath", help="Path where the graph should be stored")
    args = parser.parse_args()

    Main(args.filepath)
